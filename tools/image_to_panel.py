"""Use PhotoCraft to resize; encode a 64x64 image into HUB75 GPIO bitplanes."""
from pathlib import Path
import argparse
import hashlib
import json
import subprocess

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
CLI = Path('C:/Users/34503/Documents/Codex/Tools/PhotoCraft/photocraft-cli.exe')
BITS = 4
GAMMA = 2.2


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('source', type=Path)
    args = parser.parse_args()
    out = ROOT / 'build/image'
    out.mkdir(parents=True, exist_ok=True)
    with Image.open(args.source) as original:
        width, height = original.size
    scale = min(64 / width, 64 / height)
    size = (round(width * scale), round(height * scale))
    resized = out / 'panel-64x64.png'
    subprocess.run([
        str(CLI), 'run', str(args.source),
        '--cmd', 'image.imageSize', '--params', json.dumps({
            'width': size[0], 'height': size[1], 'resample': 'lanczos'}),
        '--cmd', 'image.canvasSize', '--params', json.dumps({
            'width': 64, 'height': 64, 'anchor': 'center', 'extensionColor': 'white'}),
        '--out', str(resized)], check=True)
    subprocess.run([str(CLI), 'info', str(resized), '--compact'], check=True)
    subprocess.run([str(CLI), 'run', str(resized),
                    '--cmd', 'image.imageSize', '--params', json.dumps({
                        'width': 512, 'height': 512, 'resample': 'nearest'}),
                    '--out', str(out / 'panel-preview.png')], check=True)
    # Gamma converts photographic sRGB values to approximate LED light duty.
    # Quantization and packing are hardware encoding, with no AI redrawing.
    with Image.open(resized) as source:
        assert source.size == (64, 64)
        rgb = list(source.convert('RGB').get_flattened_data())
    lut = [round((v / 255) ** GAMMA * 15) for v in range(256)]
    quantized = [tuple(lut[v] for v in pixel) for pixel in rgb]
    packed = []
    for plane in range(BITS):
        for row in range(32):
            for x in range(64):
                upper = quantized[row * 64 + x]
                lower = quantized[(row + 32) * 64 + x]
                mask = sum(((upper[c] >> plane) & 1) << c for c in range(3))
                mask |= sum(((lower[c] >> plane) & 1) << (c + 3) for c in range(3))
                packed.append(mask | ((0x3f & ~mask) << 16))
    # Decode every encoded pixel to verify row pairing, channel order and planes.
    for y in range(64):
        for x in range(64):
            shift = 0 if y < 32 else 3
            decoded = tuple(sum(((packed[p * 2048 + (y % 32) * 64 + x] >>
                                  (shift + c)) & 1) << p for p in range(BITS))
                            for c in range(3))
            assert decoded == quantized[y * 64 + x], (x, y)
    header = ROOT / 'firmware/panel_image.h'
    lines = ['/* Generated by tools/image_to_panel.py; logical x right, y down. */',
             '#pragma once', '#include <stdint.h>',
             '#define PANEL_COLOR_BITS 4u',
             'static const uint32_t panel_image_bsrr[4][32][64] = {']
    for p in range(4):
        lines.append('  {')
        for row in range(32):
            start = p * 2048 + row * 64
            lines.append('    {' + ','.join(f'0x{v:08x}u' for v in packed[start:start + 64]) + '},')
        lines.append('  },')
    lines.append('};')
    header.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    # A binary RGB444 copy also makes the exact LED values independently inspectable.
    (out / 'panel-rgb444.bin').write_bytes(bytes(v for pixel in quantized for v in pixel))
    metadata = {'source': str(args.source), 'source_sha256': hashlib.sha256(args.source.read_bytes()).hexdigest(),
                'source_size': [width, height], 'content_size': size, 'panel_size': [64, 64],
                'padding': 'white, centered', 'gamma': GAMMA, 'bits_per_channel': BITS,
                'unique_colors': len(set(quantized)), 'gpio_bitplane_bytes': len(packed) * 4,
                'all_4096_pixels_roundtrip_verified': True,
                'channel_mapping': 'PA0/1/2=top RGB; PA3/4/5=bottom RGB; bottom y=address+32'}
    (out / 'image-report.json').write_text(json.dumps(metadata, indent=2), encoding='utf-8')
    print(json.dumps(metadata, indent=2))


if __name__ == '__main__':
    main()
